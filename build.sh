#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
APP="${GUARD_BUILD_APP_PATH:-$ROOT/Claude Proxy Guard.app}"
SPARKLE_VERSION="2.10.1"
SPARKLE_SHA256="1a856d2a9edb8e628de88121d7be04cf0e2167f8641650b78fca00b14244cf27"
SPARKLE_ARCHIVE="$ROOT/.build/sparkle-download/Sparkle-$SPARKLE_VERSION.tar.xz"
SPARKLE_ROOT="$ROOT/.build/Sparkle-$SPARKLE_VERSION"
SIGN="${CODESIGN_IDENTITY:--}"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks" .build .build/sparkle-download
if [ ! -f "$SPARKLE_ARCHIVE" ]; then
  curl -q --fail --silent --show-error --location --max-time 120 \
    "https://github.com/sparkle-project/Sparkle/releases/download/$SPARKLE_VERSION/Sparkle-$SPARKLE_VERSION.tar.xz" \
    -o "$SPARKLE_ARCHIVE.tmp"
  mv "$SPARKLE_ARCHIVE.tmp" "$SPARKLE_ARCHIVE"
fi
ACTUAL_SPARKLE_SHA256="$(shasum -a 256 "$SPARKLE_ARCHIVE" | awk '{print $1}')"
[ "$ACTUAL_SPARKLE_SHA256" = "$SPARKLE_SHA256" ] || { echo 'Sparkle distribution hash mismatch.' >&2; exit 1; }
if [ ! -d "$SPARKLE_ROOT/Sparkle.framework" ]; then
  rm -rf "$SPARKLE_ROOT"
  mkdir -p "$SPARKLE_ROOT"
  tar -xf "$SPARKLE_ARCHIVE" -C "$SPARKLE_ROOT"
fi
ditto "$SPARKLE_ROOT/Sparkle.framework" "$APP/Contents/Frameworks/Sparkle.framework"
export CLANG_MODULE_CACHE_PATH="${TMPDIR:-/tmp}/claude-proxyguard-clang"
SDK="$(xcrun --sdk macosx --show-sdk-path)"
# The barrier helper builds first: its signed SHA-256 is embedded into the app so
# the privileged installer refuses a swapped helper binary.
for ARCH in arm64 x86_64; do
  xcrun clang -O2 -target "$ARCH-apple-macosx13.0" -isysroot "$SDK" Source/GuardDrop.c -o ".build/Drop-$ARCH"
done
lipo -create .build/Drop-arm64 .build/Drop-x86_64 -output "$APP/Contents/MacOS/GuardDrop"
codesign --force --sign "$SIGN" --identifier local.proxyguard.claude.drop "$APP/Contents/MacOS/GuardDrop"
DROP_HASH="$(shasum -a 256 "$APP/Contents/MacOS/GuardDrop" | awk '{print $1}')"
printf '// Generated by build.sh - do not edit.\nenum BarrierIntegrity { static let guardDropSHA256 = "%s" }\n' "$DROP_HASH" > .build/BarrierIntegrity.swift
for ARCH in arm64 x86_64; do
  xcrun swiftc -swift-version 5 -O -parse-as-library -sdk "$SDK" \
    -target "$ARCH-apple-macosx13.0" -module-cache-path "$CLANG_MODULE_CACHE_PATH" \
    -F "$SPARKLE_ROOT" -framework SwiftUI -framework AppKit -framework Network -framework Sparkle \
    -Xlinker -rpath -Xlinker @loader_path/../Frameworks ${GUARD_BUILD_SWIFT_FLAGS:-} \
    Source/*.swift .build/BarrierIntegrity.swift -o ".build/Guard-$ARCH"
  xcrun clang -O2 -target "$ARCH-apple-macosx13.0" -isysroot "$SDK" Source/GuardHost.c -o ".build/Host-$ARCH"
done
lipo -create .build/Host-arm64 .build/Host-x86_64 -output "$APP/Contents/MacOS/GuardHost"
codesign --force --sign "$SIGN" --identifier local.proxyguard.claude.host "$APP/Contents/MacOS/GuardHost"
lipo -create .build/Guard-arm64 .build/Guard-x86_64 -output "$APP/Contents/MacOS/ClaudeProxyGuard"
cp Resources/RuntimeBootstrap.cjs "$APP/Contents/Resources/RuntimeBootstrap.cjs"
cp Info.plist "$APP/Contents/Info.plist"
if [ -n "${GUARD_BUILD_VERSION:-}" ]; then
  /usr/libexec/PlistBuddy -c "Set :CFBundleVersion $GUARD_BUILD_VERSION" "$APP/Contents/Info.plist"
fi
if [ -n "${GUARD_BUILD_SHORT_VERSION:-}" ]; then
  /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $GUARD_BUILD_SHORT_VERSION" "$APP/Contents/Info.plist"
fi
mkdir -p "$APP/Contents/Resources/Documentation"
cp README.md SECURITY.md CHANGELOG.md "$APP/Contents/Resources/Documentation/"
cp -R docs "$APP/Contents/Resources/Documentation/"
if [ -f AppIcon.icns ]; then cp AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"; fi
FRAMEWORK="$APP/Contents/Frameworks/Sparkle.framework/Versions/B"
codesign --force --sign "$SIGN" "$FRAMEWORK/XPCServices/Downloader.xpc"
codesign --force --sign "$SIGN" "$FRAMEWORK/XPCServices/Installer.xpc"
codesign --force --sign "$SIGN" "$FRAMEWORK/Updater.app"
codesign --force --sign "$SIGN" "$FRAMEWORK/Autoupdate"
codesign --force --sign "$SIGN" "$APP/Contents/Frameworks/Sparkle.framework"
codesign --force --sign "$SIGN" --identifier local.proxyguard.claude "$APP"
codesign --verify --deep --strict "$APP"
echo "Built: $APP"
